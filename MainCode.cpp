string getli(stringstream &ss)
{ // ???�?�?�?�?????????��????��??�?�?
    string cell;
    if (!getline(ss, cell, ','))
        return ""; // �????失�???????�空

    // 移�?��??串�??�????空�?��??�???��??�????�?�? \r, \n, tab�?
    cell.erase(cell.find_last_not_of(" \n\r\t") + 1);
    cell.erase(0, cell.find_first_not_of(" \n\r\t"));

    return cell;
}

